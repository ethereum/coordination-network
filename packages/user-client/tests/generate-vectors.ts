/**
 * Deterministic generator for `tests/vectors/registration-vectors.json`:
 * re-running on unchanged library code must produce a byte-identical file.
 * Run with:
 *
 *     yarn tsx packages/user-client/tests/generate-vectors.ts
 */

import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"
import { deriveKeys, META_STEALTH_ADDRESS_LENGTH, META_STEALTH_URI_PREFIX } from "@coordination-network/identity"
import { metaStealthAddressFromKeys, displayMetaStealthAddress } from "../src/meta"
import { identityRegistryDomainSeparator, registerIdentityStructHash, registerIdentityDigest } from "../src/eip712"
import { signRegisterIdentity } from "../src/request"
import type { ChainDomain, Hex } from "../src/types"
import {
    SCHEME_ID,
    IDENTITY_REGISTRY_DOMAIN_NAME,
    IDENTITY_REGISTRY_DOMAIN_VERSION,
    REGISTER_IDENTITY_TYPE,
    EIP712_DOMAIN_TYPE
} from "../src/constants"

const DOMAIN: ChainDomain = {
    chainId: 31337,
    verifyingContract: `0x${"04".repeat(19)}e7`
}

const SECRETS: Hex[] = [
    `0x${"00".repeat(31)}01`, // smallest non-trivial secret
    `0x${"ff".repeat(32)}`, // all ones
    `0x${"01".repeat(32)}`, // uniform 0x01
    `0x${"02".repeat(32)}`, // uniform 0x02
    `0x${"33".repeat(32)}`, // uniform 0x33
    `0x${"a5".repeat(32)}`, // uniform 0xa5
    `0x${"10".repeat(32)}` // uniform 0x10, the one secret here whose signature recovers with v = 28
]

function buildVector(deviceSecret: Hex) {
    const keys = deriveKeys(deviceSecret)
    const metaStealthAddress = metaStealthAddressFromKeys(keys)
    const domainSeparator = identityRegistryDomainSeparator(DOMAIN)
    const structHash = registerIdentityStructHash(keys.networkId, metaStealthAddress)
    const digest = registerIdentityDigest(DOMAIN, keys.networkId, metaStealthAddress)
    const signature = signRegisterIdentity(keys.account.privateKey, digest)

    return {
        deviceSecret,
        networkId: keys.networkId,
        metaStealthAddress,
        displayMetaStealthAddress: displayMetaStealthAddress(metaStealthAddress),
        domainSeparator,
        structHash,
        digest,
        signature
    }
}

const document = {
    _comment:
        "Deterministic registration test vectors for @coordination-network/user-client. " +
        "Generated by tests/generate-vectors.ts; do not edit by hand. " +
        "Regenerate with `yarn tsx packages/user-client/tests/generate-vectors.ts`.",
    scheme: {
        domain: DOMAIN,
        schemeId: SCHEME_ID,
        metaStealthAddressLength: META_STEALTH_ADDRESS_LENGTH,
        identityRegistryDomainName: IDENTITY_REGISTRY_DOMAIN_NAME,
        identityRegistryDomainVersion: IDENTITY_REGISTRY_DOMAIN_VERSION,
        registerIdentityType: REGISTER_IDENTITY_TYPE,
        eip712DomainType: EIP712_DOMAIN_TYPE,
        stealthMetaAddressPrefix: META_STEALTH_URI_PREFIX,
        algorithm:
            "ERC-6538 scheme 1 meta-address + EIP-712 RegisterIdentity consent digest, domain-bound to the IdentityRegistry deployment"
    },
    vectors: SECRETS.map(buildVector)
}

const outputPath = join(dirname(fileURLToPath(import.meta.url)), "vectors", "registration-vectors.json")

writeFileSync(outputPath, `${JSON.stringify(document, null, 4)}\n`)

// eslint-disable-next-line no-console
console.log(`Wrote ${document.vectors.length} vectors to ${outputPath}`)
