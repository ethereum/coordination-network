/**
 * Deterministic generator for `tests/vectors/eddsa-vectors.json`: re-running
 * on unchanged library code must produce a byte-identical file. Run with:
 *
 *     yarn tsx packages/identity/tests/generate-eddsa-vectors.ts
 */

import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"
import { p256 } from "@noble/curves/p256"
import { deriveEddsaKeypair, eddsaPeerPointBytes, EDDSA_PEER_POINT_HEX } from "../src"
import { DOMAIN_EDDSA, DOMAIN_EDDSA_PEER } from "../src/constants"
import { bytesToHex } from "../src/bytes"
import { seededP256Key } from "./helpers"

/**
 * `seededP256Key(0..11)` — indices 0-5 deliberately coincide with the
 * `confirmationKey` hardware stand-ins in `binding-vectors.json`. This is
 * intentional (both vector sets exercise the same seeded TEST P-256 keys as
 * hardware stand-ins): do not "fix" it by reindexing.
 */
const HARDWARE_KEY_INDICES = Array.from({ length: 12 }, (_unused, i) => i)

function buildVector(index: number) {
    const { privateKey: hardwarePrivateKey, publicKey: hardwarePublicKey } = seededP256Key(index)
    const ecdhSharedSecret = p256.getSharedSecret(hardwarePrivateKey, eddsaPeerPointBytes(), true).slice(1)
    const keys = deriveEddsaKeypair(ecdhSharedSecret)

    return {
        hardwarePrivateKey: bytesToHex(hardwarePrivateKey),
        hardwarePublicKey: bytesToHex(hardwarePublicKey),
        ecdhSharedSecret: bytesToHex(ecdhSharedSecret),
        seed: keys.seed,
        secretScalar: keys.secretScalar.toString(10),
        publicKey: [keys.publicKey[0].toString(10), keys.publicKey[1].toString(10)] as [string, string],
        commitment: keys.commitment.toString(10)
    }
}

const document = {
    _comment:
        "Deterministic Baby Jubjub EdDSA fifth-key test vectors for @coordination-network/identity. " +
        "hardwarePrivateKey/hardwarePublicKey are seeded TEST P-256 keys standing in for the hardware " +
        "confirmation key B; real hwPriv is non-exportable Keystore-resident. Indices 0-5 intentionally " +
        "coincide with binding-vectors.json's confirmationKey stand-ins. " +
        "Generated by tests/generate-eddsa-vectors.ts; do not edit by hand. " +
        "Regenerate with `yarn tsx packages/identity/tests/generate-eddsa-vectors.ts`.",
    scheme: {
        version: "v1",
        domainEddsa: DOMAIN_EDDSA,
        domainEddsaPeer: DOMAIN_EDDSA_PEER,
        peerPoint: EDDSA_PEER_POINT_HEX,
        peerPointDerivation:
            "hashToCurve(utf8(domainEddsaPeer)) — RFC 9380 P256_XMD:SHA-256_SSWU_RO_, suite-default DST",
        sharedSecret:
            "X(hardwarePrivateKey . peerPoint), 32 BE bytes — noble getSharedSecret(priv, peerPoint, true).slice(1)",
        seedHash: "keccak256",
        curve: "baby-jubjub",
        scalarDerivation: "blake512-prune-shift (zk-kit eddsa-poseidon 1.0.4)",
        commitment: "poseidon2([x,y]) (poseidon-lite 0.3.0)"
    },
    vectors: HARDWARE_KEY_INDICES.map(buildVector)
}

const outputPath = join(dirname(fileURLToPath(import.meta.url)), "vectors", "eddsa-vectors.json")

writeFileSync(outputPath, `${JSON.stringify(document, null, 4)}\n`)

// eslint-disable-next-line no-console
console.log(`Wrote ${document.vectors.length} vectors to ${outputPath}`)
