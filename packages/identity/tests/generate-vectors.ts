/**
 * Deterministic generator for `tests/vectors/derivation-vectors.json`:
 * re-running on unchanged library code must produce a byte-identical file.
 * Run with:
 *
 *     yarn tsx packages/identity/tests/generate-vectors.ts
 */

import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"
import { secp256k1 } from "@noble/curves/secp256k1"
import { deriveKeys } from "../src"
import type { DerivedKeys, Hex, Secp256k1Keypair } from "../src/types"
import {
    KEY_DERIVATION_VERSION,
    FIXED_DOMAIN_MSG,
    DOMAIN_ACCOUNT,
    DOMAIN_AUTH,
    DOMAIN_NETWORK_ID
} from "../src/constants"
import { bytesToHex } from "../src/bytes"
import { seededSecret, signWithRecovery } from "./helpers"

function incremental(): Hex {
    return bytesToHex(Uint8Array.from({ length: 32 }, (_unused, i) => i))
}

function reverseIncremental(): Hex {
    return bytesToHex(Uint8Array.from({ length: 32 }, (_unused, i) => 31 - i))
}

const SECRETS: Hex[] = [
    `0x${"00".repeat(31)}01`, // smallest non-trivial secret
    `0x${"ff".repeat(32)}`, // all ones
    `0x${"01".repeat(32)}`, // uniform 0x01
    `0x${"02".repeat(32)}`, // uniform 0x02
    incremental(),
    reverseIncremental(),
    seededSecret(0),
    seededSecret(1),
    seededSecret(2),
    seededSecret(3),
    seededSecret(4),
    seededSecret(5)
]

function keypairFields(keypair: Secp256k1Keypair) {
    return {
        privateKey: keypair.privateKey,
        publicKey: keypair.publicKey,
        uncompressedPublicKey: keypair.uncompressedPublicKey
    }
}

function buildVector(deviceSecret: Hex) {
    const keys: DerivedKeys = deriveKeys(deviceSecret)
    const signature = signWithRecovery(keys.account.privateKey)

    return {
        deviceSecret,
        version: keys.version,
        networkId: keys.networkId,
        memberNetworkId: keys.memberNetworkId,
        account: keypairFields(keys.account),
        signature: {
            r: signature.r,
            s: signature.s,
            v: signature.v,
            compact: signature.compact
        },
        spending: keypairFields(keys.spending),
        viewing: keypairFields(keys.viewing),
        auth: keypairFields(keys.auth)
    }
}

const document = {
    _comment:
        "Deterministic v2 derivation test vectors for @coordination-network/identity. " +
        "Generated by tests/generate-vectors.ts; do not edit by hand. " +
        "Regenerate with `yarn tsx packages/identity/tests/generate-vectors.ts`.",
    scheme: {
        version: KEY_DERIVATION_VERSION,
        fixedDomainMsg: FIXED_DOMAIN_MSG,
        domainAccount: DOMAIN_ACCOUNT,
        domainAuth: DOMAIN_AUTH,
        domainNetworkId: DOMAIN_NETWORK_ID,
        curve: "secp256k1",
        hash: "keccak256",
        groupOrder: `0x${secp256k1.CURVE.n.toString(16)}`
    },
    vectors: SECRETS.map(buildVector)
}

const outputPath = join(dirname(fileURLToPath(import.meta.url)), "vectors", "derivation-vectors.json")

writeFileSync(outputPath, `${JSON.stringify(document, null, 4)}\n`)

// eslint-disable-next-line no-console
console.log(`Wrote ${document.vectors.length} vectors to ${outputPath}`)
