/**
 * Deterministic generator for `tests/vectors/stealth-vectors.json`:
 * re-running on unchanged library code must produce a byte-identical file.
 * Run with:
 *
 *     yarn tsx packages/identity/tests/generate-stealth-vectors.ts
 */

import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"
import { secp256k1 } from "@noble/curves/secp256k1"

import { deriveKeys } from "../src"
import type { Hex } from "../src/types"
import { bytesToHex } from "../src/bytes"
import { META_STEALTH_ADDRESS_LENGTH, META_STEALTH_URI_PREFIX } from "../src/constants"
import { computeSharedSecret } from "../src/stealthAddresses/computeSharedSecret"
import { getViewTag } from "../src/stealthAddresses/getViewTag"
import { generateStealthAddress } from "../src/stealthAddresses/generateStealthAddress"
import { generateStealthPrivateKey } from "../src/stealthAddresses/generateStealthPrivateKey"
import { encodeMetaStealthAddress } from "../src/stealthAddresses/encodeMetaStealthAddress"
import { seededSecret } from "./helpers"
import { seededEphemeralKey } from "./stealthAddresses/helpers"

const DEVICE_SECRETS: Hex[] = [
    `0x${"00".repeat(31)}01`, // smallest secret
    `0x${"ff".repeat(32)}`, // all ones
    `0x${"01".repeat(32)}`, // uniform 0x01
    bytesToHex(Uint8Array.from({ length: 32 }, (_unused, i) => i)), // incremental
    seededSecret(0),
    seededSecret(1),
    seededSecret(2),
    seededSecret(3)
]

function buildVector(deviceSecret: Hex, index: number) {
    const { spending, viewing } = deriveKeys(deviceSecret)
    const ephemeral = seededEphemeralKey(index)

    const hashedSharedSecret = computeSharedSecret({
        privateKey: ephemeral.privateKey,
        publicKey: viewing.publicKey
    })

    return {
        deviceSecret,
        spendingPublicKey: spending.publicKey,
        viewingPublicKey: viewing.publicKey,
        ephemeralPrivateKey: ephemeral.privateKey,
        ephemeralPublicKey: ephemeral.publicKey,
        hashedSharedSecret: bytesToHex(hashedSharedSecret),
        viewTag: getViewTag(hashedSharedSecret),
        stealthAddress: generateStealthAddress({
            spendingPublicKey: spending.publicKey,
            viewingPublicKey: viewing.publicKey,
            ephemeralPrivateKey: ephemeral.privateKey
        }),
        stealthPrivateKey: generateStealthPrivateKey({
            ephemeralPublicKey: ephemeral.publicKey,
            viewingPrivateKey: viewing.privateKey,
            spendingPrivateKey: spending.privateKey
        }),
        metaStealthAddress: encodeMetaStealthAddress({
            spendingPublicKey: spending.publicKey,
            viewingPublicKey: viewing.publicKey
        })
    }
}

const document = {
    _comment:
        "Deterministic ERC-5564 scheme 1 stealth-address test vectors for @coordination-network/identity. " +
        "Conformance is separately cross-checked live against @scopelift/stealth-address-sdk. " +
        "Generated by tests/generate-stealth-vectors.ts; do not edit by hand. " +
        "Regenerate with `yarn tsx packages/identity/tests/generate-stealth-vectors.ts`.",
    scheme: {
        schemeId: 1,
        curve: "secp256k1",
        hash: "keccak256",
        sharedSecretEncoding: "SEC1 compressed (33 bytes)",
        metaStealthAddressLength: META_STEALTH_ADDRESS_LENGTH,
        uriPrefix: META_STEALTH_URI_PREFIX,
        groupOrder: `0x${secp256k1.Point.CURVE().n.toString(16)}`
    },
    vectors: DEVICE_SECRETS.map(buildVector)
}

const outputPath = join(dirname(fileURLToPath(import.meta.url)), "vectors", "stealth-vectors.json")

writeFileSync(outputPath, `${JSON.stringify(document, null, 4)}\n`)

// eslint-disable-next-line no-console
console.log(`Wrote ${document.vectors.length} vectors to ${outputPath}`)
