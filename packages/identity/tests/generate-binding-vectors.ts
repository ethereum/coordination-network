/**
 * Deterministic generator for `tests/vectors/binding-vectors.json`:
 * re-running on unchanged library code must produce a byte-identical file.
 * Run with:
 *
 *     yarn tsx packages/identity/tests/generate-binding-vectors.ts
 *
 * `sigB` here is deterministic RFC-6979 P-256 from a seeded test key, not
 * production `sig_B`'s randomized platform ECDSA.
 */

import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"
import { p256 } from "@noble/curves/p256"
import { keccak_256 } from "@noble/hashes/sha3"
import {
    deriveKeys,
    computeConfirmationKeyHash,
    buildBindingMessages,
    signAccountBinding,
    BINDING_NONCE_LENGTH
} from "../src"
import type { Hex } from "../src/types"
import { bytesToHex, concatBytes, utf8ToBytes } from "../src/bytes"
import { seededCommitment, seededNonce, seededP256Key } from "./helpers"
import derivationVectorsDocument from "./vectors/derivation-vectors.json"
import eddsaVectorsDocument from "./vectors/eddsa-vectors.json"

// Rebuilt rather than imported: the library's eip191Digest is not a public export.
function eip191Digest(message: Uint8Array): Uint8Array {
    const prefix = utf8ToBytes(`\x19Ethereum Signed Message:\n${String(message.length)}`)

    return keccak_256(concatBytes(prefix, message))
}

/** The first six device secrets already pinned by the derivation vectors. */
const DEVICE_SECRETS: Hex[] = derivationVectorsDocument.vectors.slice(0, 6).map((vector) => vector.deviceSecret as Hex)

/**
 * `eddsa-vectors.json` indices 0-5 share their hardware key with these vectors, so this is the commitment
 * that holder signs for.
 */
function holderKeyCommitmentFor(index: number): Hex {
    return `0x${BigInt(eddsaVectorsDocument.vectors[index].commitment).toString(16).padStart(64, "0")}`
}

/** Opaque here; the credential layer computes the real value from the issuer and scope. */
function requestCommitmentFor(index: number): Hex {
    return bytesToHex(seededCommitment("vector-request", index))
}

function buildVector(deviceSecret: Hex, index: number) {
    const keys = deriveKeys(deviceSecret)
    const nonce = seededNonce(index)
    const { privateKey: devicePrivateKey, publicKey: confirmationKey } = seededP256Key(index)

    const holderKeyCommitment = holderKeyCommitmentFor(index)
    const requestCommitment = requestCommitmentFor(index)

    const { networkId, deviceBindingMessage, accountBindingMessage } = buildBindingMessages(
        nonce,
        keys.account.uncompressedPublicKey,
        confirmationKey,
        holderKeyCommitment,
        requestCommitment
    )

    const accountDigest = eip191Digest(accountBindingMessage)
    const { signature: sigA } = signAccountBinding(keys.account.privateKey, nonce, confirmationKey)
    const sigB = p256.sign(deviceBindingMessage, devicePrivateKey, { prehash: true }).toCompactRawBytes()

    return {
        deviceSecret,
        nonce: bytesToHex(nonce),
        confirmationKey: bytesToHex(confirmationKey),
        confirmationKeyHash: computeConfirmationKeyHash(confirmationKey),
        networkId,
        holderKeyCommitment,
        requestCommitment,
        deviceBindingMessage: bytesToHex(deviceBindingMessage),
        accountBindingMessage: bytesToHex(accountBindingMessage),
        accountDigest: bytesToHex(accountDigest),
        sigA,
        sigB: bytesToHex(sigB)
    }
}

const document = {
    _comment:
        "Deterministic credential-binding test vectors for @coordination-network/identity. " +
        "Generated by tests/generate-binding-vectors.ts; do not edit by hand. " +
        "Regenerate with `yarn tsx packages/identity/tests/generate-binding-vectors.ts`. " +
        "sigB is a deterministic RFC-6979 P-256 signature by a seeded TEST key; real sig_B is " +
        "randomized platform ECDSA (Secure Enclave / Android Keystore / WebCrypto). " +
        "holderKeyCommitment is eddsa-vectors.json[i].commitment as 32-byte big-endian. " +
        "requestCommitment is an opaque seeded value here; the credential layer computes the real one from the issuer and scope.",
    scheme: {
        bindingNonceLength: BINDING_NONCE_LENGTH,
        confirmationKeyHash: "RFC7638-JWK-thumbprint",
        sigA: "EIP-191 + RFC6979 lowS secp256k1 compact",
        sigB: "ECDSA-P256-SHA256"
    },
    vectors: DEVICE_SECRETS.map((deviceSecret, index) => buildVector(deviceSecret, index))
}

const outputPath = join(dirname(fileURLToPath(import.meta.url)), "vectors", "binding-vectors.json")

writeFileSync(outputPath, `${JSON.stringify(document, null, 4)}\n`)

// eslint-disable-next-line no-console
console.log(`Wrote ${document.vectors.length} vectors to ${outputPath}`)
